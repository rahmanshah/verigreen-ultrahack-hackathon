"""Count the human adjudication verdicts by pair (not by row). Counts only; no percentages, no accuracy figure.

    uv run python scripts/extraction_eval/count_verdicts.py

Reads data/extraction_eval/run_001_scoring/adjudication_verdicts.csv (built by build_adjudication_verdicts.py) and writes
data/extraction_eval/run_001_scoring/verdict_counts.md. No API call.
"""
import argparse
import csv
import sys
from collections import Counter, OrderedDict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCORING_DIR = ROOT / "data" / "extraction_eval" / "run_001_scoring"
IN_CSV = SCORING_DIR / "adjudication_verdicts.csv"
OUT_MD = SCORING_DIR / "verdict_counts.md"

MAIN_TOKENS = ["vintage_or_restatement", "boundary_or_method", "year_column_wrong", "extraction_correct"]
OTHER_TOKENS = ["unclear", "our_verified_value_wrong", "extraction_wrong"]
GROUPS = ["verified_mismatch", "ambiguous_verified", "ambiguous_extracted", "spike"]
SCORER_LABELS = ["vintage_difference", "year_mapping_suspect"]

HEADER = """# Adjudication verdict counts (run_001)

Generated by `scripts/extraction_eval/count_verdicts.py` from `adjudication_verdicts.csv`. Counts only.

- The verdict token `extraction_correct` and combined forms such as `extraction_correct+year_column_wrong` were added by
  the reviewer during adjudication; they were not in the original verdict list.
- The review was done by one person with suggested verdicts in front of them. It is a first review, not an independent one.
- The 57 matched pairs were not reviewed by a human.
- Counts are by pair (one pair = one verified value and its candidate extracted rows), not by row, unless a table says rows.
- A combined verdict such as `extraction_correct+year_column_wrong` counts once under each of its tokens, so token counts
  can add up to more than the number of pairs.
"""


def group_of(row):
    return "spike" if row["spike_not_blind"] == "True" else row["category"]


def load_pairs(path):
    with path.open(encoding="utf-8-sig", newline="") as f:
        rows = list(csv.DictReader(f))
    by_pair = OrderedDict()
    for r in rows:
        by_pair.setdefault(r["pair_id"], []).append(r)
    pairs = []
    for pid in sorted(by_pair):
        rs = by_pair[pid]
        for col in ("human_verdict", "human_notes", "category", "spike_not_blind", "labels"):
            if len({r[col] for r in rs}) != 1:
                sys.exit(f"stopped: {pid} has differing values in column {col}")
        r0 = rs[0]
        verdict = r0["human_verdict"]
        pairs.append({
            "pair_id": pid, "group": group_of(r0), "verdict": verdict,
            "tokens": verdict.split("+") if verdict else [], "labels": r0["labels"],
            "rows": len(rs), "company": r0["company"], "year": r0["year"], "scope": r0["scope"],
            "notes": r0["human_notes"],
        })
    return pairs, len(rows)


def table(headers, body):
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(str(c) for c in row) + " |" for row in body]
    return "\n".join(out)


def build_md(pairs, n_rows):
    judged = [p for p in pairs if p["group"] != "spike"]
    spikes = [p for p in pairs if p["group"] == "spike"]
    if any(p["verdict"] for p in spikes) or any(not p["verdict"] for p in judged):
        sys.exit("stopped: a non-spike pair has no verdict or a spike pair has one")
    used = Counter(t for p in judged for t in p["tokens"])
    token_order = MAIN_TOKENS + [t for t in OTHER_TOKENS if used[t]]
    unknown = sorted(set(used) - set(MAIN_TOKENS) - set(OTHER_TOKENS))
    if unknown:
        sys.exit(f"stopped: unknown tokens {unknown}")
    md = [HEADER]

    md.append("## Scope\n")
    md.append(f"{len(pairs)} pairs in {n_rows} rows: {len(judged)} adjudicated, {len(spikes)} not adjudicated "
              "(spike pairs, not blind). The 57 matched pairs are not in this file.\n")

    md.append("## Pairs per category\n")
    body = [(g, sum(p["group"] == g for p in pairs), sum(p["rows"] for p in pairs if p["group"] == g)) for g in GROUPS]
    md.append(table(["category", "pairs", "rows"], body))
    md.append("\n`spike` = `ambiguous_extracted` rows flagged `spike_not_blind`; listed separately below and left out of all "
              "verdict counts.\n")

    md.append("## Pairs per verdict token, by category\n")
    md.append("Combined verdicts count once under each token.\n")
    body = []
    for g in GROUPS[:3]:
        gp = [p for p in judged if p["group"] == g]
        body.append([g, len(gp)] + [sum(t in p["tokens"] for p in gp) for t in token_order])
    body.append(["all adjudicated", len(judged)] + [used[t] for t in token_order])
    md.append(table(["category", "pairs"] + token_order, body))
    md.append("\nTokens outside the four main ones: "
              + (", ".join(f"{t} ({used[t]})" for t in OTHER_TOKENS if used[t]) or "none") + ".\n")

    md.append("## Pairs per exact verdict string, by category\n")
    strings = Counter((p["group"], p["verdict"]) for p in judged)
    body = [(g, v, n) for (g, v), n in sorted(strings.items(), key=lambda kv: (GROUPS.index(kv[0][0]), -kv[1], kv[0][1]))]
    md.append(table(["category", "verdict string", "pairs"], body))
    md.append("")

    md.append("## Pairs with `year_column_wrong`\n")
    body = []
    for g in GROUPS[:3]:
        yp = [p for p in judged if g == p["group"] and "year_column_wrong" in p["tokens"]]
        multi = [p for p in yp if p["rows"] > 1]
        body.append((g, len(yp), len(multi), ", ".join(p["pair_id"] for p in yp) or "-"))
    allp = [p for p in judged if "year_column_wrong" in p["tokens"]]
    body.append(("all", len(allp), sum(p["rows"] > 1 for p in allp), ", ".join(p["pair_id"] for p in allp)))
    md.append(table(["category", "pairs with token", "of which more than one candidate row", "pair ids"], body))
    md.append("")

    md.append("## Rows per verdict string\n")
    rows_by = Counter()
    for p in pairs:
        rows_by[p["verdict"] or "(none: not adjudicated)"] += p["rows"]
    body = sorted(rows_by.items(), key=lambda kv: (-kv[1], kv[0]))
    md.append(table(["verdict string", "rows"], body) + f"\n\nTotal rows: {sum(rows_by.values())}.\n")

    md.append("## Scorer labels next to the reviewer verdict\n")
    md.append("Listing only. The scorer label is automatic (`labels` column of `adjudication_list.csv`); an empty label "
              "means the scorer put neither `vintage_difference` nor `year_mapping_suspect` on the pair.\n")
    labelled = [p for p in judged if any(l in p["labels"].split(";") for l in SCORER_LABELS)]
    md.append(f"### Pairs the scorer labelled ({len(labelled)})\n")
    md.append(table(["pair", "company", "year", "scope", "scorer labels", "reviewer verdict"],
                    [(p["pair_id"], p["company"], p["year"], p["scope"], p["labels"], p["verdict"]) for p in labelled]))
    md.append("\n### All adjudicated pairs\n")
    md.append(table(["pair", "category", "candidate rows", "scorer labels", "reviewer verdict"],
                    [(p["pair_id"], p["group"], p["rows"], p["labels"] or "(none)", p["verdict"]) for p in judged]))
    md.append("")

    md.append("## Spike pairs (not adjudicated)\n")
    md.append(table(["pair", "company", "year", "scope", "candidate rows", "note"],
                    [(p["pair_id"], p["company"], p["year"], p["scope"], p["rows"], p["notes"]) for p in spikes]))
    md.append("")
    return "\n".join(md)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--in", dest="inp", type=Path, default=IN_CSV)
    ap.add_argument("--out", type=Path, default=OUT_MD)
    args = ap.parse_args()
    pairs, n_rows = load_pairs(args.inp)
    md = build_md(pairs, n_rows)
    args.out.write_text(md, encoding="utf-8", newline="\n")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
